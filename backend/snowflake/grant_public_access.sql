-- Step 1: Switch to Admin Role to configure grants
USE ROLE ACCOUNTADMIN;

-- Ensure Warehouse exists and is sized for cost-efficiency
CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH
    WITH WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- Grant Warehouse Usage to Role PUBLIC
GRANT USAGE, OPERATE ON WAREHOUSE COMPUTE_WH TO ROLE PUBLIC;

-- Step 2: Grant Database & Schema Access to Role PUBLIC
GRANT USAGE ON DATABASE FARMPRICE_DB TO ROLE PUBLIC;
GRANT USAGE ON SCHEMA FARMPRICE_DB.AGRICULTURE TO ROLE PUBLIC;
GRANT USAGE ON SCHEMA FARMPRICE_DB.ANALYTICS TO ROLE PUBLIC;

-- Step 3: Grant Table & View Read Permissions to Role PUBLIC
GRANT SELECT ON ALL TABLES IN SCHEMA FARMPRICE_DB.AGRICULTURE TO ROLE PUBLIC;
GRANT SELECT ON FUTURE TABLES IN SCHEMA FARMPRICE_DB.AGRICULTURE TO ROLE PUBLIC;
GRANT SELECT ON ALL VIEWS IN SCHEMA FARMPRICE_DB.AGRICULTURE TO ROLE PUBLIC;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA FARMPRICE_DB.AGRICULTURE TO ROLE PUBLIC;

GRANT SELECT ON ALL TABLES IN SCHEMA FARMPRICE_DB.ANALYTICS TO ROLE PUBLIC;
GRANT SELECT ON FUTURE TABLES IN SCHEMA FARMPRICE_DB.ANALYTICS TO ROLE PUBLIC;
GRANT SELECT ON ALL VIEWS IN SCHEMA FARMPRICE_DB.ANALYTICS TO ROLE PUBLIC;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA FARMPRICE_DB.ANALYTICS TO ROLE PUBLIC;

-- Optional: Grant Write / Ingestion privileges for automated data syncing
GRANT INSERT, UPDATE ON ALL TABLES IN SCHEMA FARMPRICE_DB.AGRICULTURE TO ROLE PUBLIC;
GRANT INSERT, UPDATE ON FUTURE TABLES IN SCHEMA FARMPRICE_DB.AGRICULTURE TO ROLE PUBLIC;

