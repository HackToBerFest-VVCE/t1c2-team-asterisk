from typing import List, Dict, Any

# Unit Conversion Constants
HECTARES_TO_ACRES = 2.47105381
KG_PER_QUINTAL = 100.0

def convert_kg_ha_to_quintals_acre(kg_ha: float) -> float:
    """Converts yield in kg/hectare to quintals/acre with precision."""
    return round(kg_ha / (KG_PER_QUINTAL * HECTARES_TO_ACRES), 2)

